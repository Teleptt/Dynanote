import {
  AIGenerationRequest,
  AIGenerationResponse,
  ProviderCapability,
  ProviderConfig,
  TestConnectionResult
} from '../../types';
import { IAIProvider } from './provider-interface';
import { SYSTEM_PROMPT } from './prompt-templates';
import { extractAndValidateSimulation } from './json-cleaner';

export class OllamaProvider implements IAIProvider {
  id = 'ollama' as const;
  name = 'Ollama (Local LLM)';
  description = 'Private, local execution with zero internet required using Llama 3, DeepSeek, or Llava.';

  capabilities: ProviderCapability = {
    supportsVision: true,
    supportsStreaming: false,
    supportsJsonSchema: true,
    defaultModel: 'llama3',
    modelPlaceholder: 'e.g. llama3.2, mistral, deepseek-r1:8b, llava, etc.',
    allowsAPIKey: true,
    apiKeyOptional: true, // Optional for local host, useful if behind an auth proxy
    defaultBaseURL: 'http://localhost:11434'
  };

  async generateSimulation(
    request: AIGenerationRequest,
    config: ProviderConfig,
    _globalSettings?: { temperature?: number }
  ): Promise<AIGenerationResponse> {
    const baseURL = (config.baseURL || this.capabilities.defaultBaseURL)!.replace(/\/+$/, '');
    const model = (config.model && config.model.trim()) || this.capabilities.defaultModel || 'llama3';
    const url = `${baseURL}/api/generate`;

    request.onStatusUpdate?.({
      step: 'preparing',
      message: `Formatting prompt for local Ollama model (${model})...`,
      provider: this.id
    });

    const prompt = `${SYSTEM_PROMPT}\n\nUser Notes:\n${request.noteContent}\n${
      request.selectedText ? `Selected Focus:\n${request.selectedText}\n` : ''
    }${request.instructions ? `Instructions: ${request.instructions}\n` : ''}\nRespond ONLY in valid JSON:`;

    const images: string[] = [];
    if (request.sketchImageBase64) {
      const cleanBase64 = request.sketchImageBase64.replace(/^data:image\/\w+;base64,/, '');
      images.push(cleanBase64);
    }

    const payload: any = {
      model,
      prompt,
      format: 'json',
      stream: false
    };

    if (images.length > 0) {
      payload.images = images;
    }

    request.onStatusUpdate?.({
      step: 'synthesizing',
      message: `Generating on local GPU/CPU via Ollama (${model})...`,
      provider: this.id
    });

    const headers: Record<string, string> = {
      'Content-Type': 'application/json'
    };
    if (config.apiKey && config.apiKey.trim()) {
      headers['Authorization'] = `Bearer ${config.apiKey.trim()}`;
    }

    const res = await fetch(url, {
      signal: request.signal,
      method: 'POST',
      headers,
      body: JSON.stringify(payload)
    });

    if (!res.ok) {
      const err = await res.text();
      throw new Error(`Ollama Error (${res.status}): ${err}. Ensure Ollama is running with CORS enabled (OLLAMA_ORIGINS=*).`);
    }

    request.onStatusUpdate?.({
      step: 'parsing',
      message: 'Validating local model JSON output...',
      provider: this.id
    });

    const data = await res.json();
    const text = data.response;
    const cleaned = extractAndValidateSimulation(text, 'Visualization generated by local Ollama model.');

    return {
      spec: cleaned.spec,
      explanation: cleaned.explanation,
      proposal: cleaned.proposal,
      providerUsed: this.id,
      modelUsed: model
    };
  }

  async testConnection(config: ProviderConfig): Promise<TestConnectionResult> {
    const baseURL = (config.baseURL || this.capabilities.defaultBaseURL)!.replace(/\/+$/, '');
    const url = `${baseURL}/api/tags`;

    const headers: Record<string, string> = {};
    if (config.apiKey && config.apiKey.trim()) {
      headers['Authorization'] = `Bearer ${config.apiKey.trim()}`;
    }

    const startTime = performance.now();
    try {
      const res = await fetch(url, { headers });
      const latency = Math.round(performance.now() - startTime);

      if (!res.ok) {
        return { success: false, message: `HTTP ${res.status} from Ollama`, latencyMs: latency };
      }

      const data = await res.json();
      const count = Array.isArray(data.models) ? data.models.length : 0;
      return {
        success: true,
        message: `Ollama is running (${count} local model${count === 1 ? '' : 's'} installed)`,
        latencyMs: latency
      };
    } catch (e: any) {
      return {
        success: false,
        message: `Could not reach Ollama at ${baseURL}. Run: OLLAMA_ORIGINS="*" ollama serve`
      };
    }
  }
}
